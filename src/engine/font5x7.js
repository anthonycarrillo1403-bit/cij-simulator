const ACCENTS = { Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ü: 'U', á: 'a', é: 'e', í: 'i', ó: 'o', ú: 'u', ü: 'u' }
// Ñ / ñ dibujadas con tilde en la fila superior
GLYPHS['Ñ'] = [0x7e, 0x05, 0x09, 0x11, 0x7e]
GLYPHS['ñ'] = [0x7a, 0x09, 0x05, 0x05, 0x78]

export function glyphColumns(ch) {
  const g = GLYPHS[ch] || GLYPHS[ACCENTS[ch]] || GLYPHS['?']
  return g
}

// Fuentes Imaje simuladas: nombre comercial, altura en puntos y factor de escala.
export const FONTS = {
  '5x5': { label: '5 x 5', h: 5, sx: 1, sy: 5 / 7 },
  '7x5': { label: '7 x 5', h: 7, sx: 1, sy: 1 },
  '9x7': { label: '9 x 7', h: 9, sx: 1.4, sy: 9 / 7 },
  '11x9': { label: '11 x 9', h: 11, sx: 1.8, sy: 11 / 7 },
  '16x10': { label: '16 x 10', h: 16, sx: 2, sy: 16 / 7 },
  '24x16': { label: '24 x 16', h: 24, sx: 3.2, sy: 24 / 7 },
}

// Devuelve una matriz de columnas (cada columna = array booleano de altura h,
// índice 0 = punto inferior, como se numeran las gotas en una trama).
export function rasterizeText(text, fontKey = '7x5', bold = 1) {
  const font = FONTS[fontKey] || FONTS['7x5']
  const cols = []
  const srcW = 5
  const outW = Math.max(1, Math.round(srcW * font.sx))
  for (const ch of [...text]) {
    const g = glyphColumns(ch)
    for (let x = 0; x < outW; x++) {
      const sxCol = g[Math.min(srcW - 1, Math.floor((x * srcW) / outW))]
      const col = new Array(font.h).fill(false)
      for (let y = 0; y < font.h; y++) {
        // y desde arriba en la fuente fuente; convertir a índice desde abajo
        const srcRow = Math.min(6, Math.floor((y * 7) / font.h))
        col[font.h - 1 - y] = Boolean(sxCol & (1 << srcRow))
      }
      // Dilatación (negrita): repetición de la trama n veces
      for (let b = 0; b < bold; b++) cols.push(col)
    }
    // trama vacía entre caracteres
    cols.push(new Array(font.h).fill(false))
  }
  return { cols, h: font.h }
}
